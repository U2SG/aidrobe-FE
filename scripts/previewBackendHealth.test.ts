import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { probeBackend, resolveProfile, hash } = require('./check-preview-backend.cjs');
const spec = { openapi: '3.1.0', paths: { '/v1/analytics/events': { post: {} } } };
const valid = async (url: URL) => Response.json(url.pathname === '/openapi.json' ? spec : { status: url.pathname === '/healthz' ? 'ok' : 'ready' });
const base = { baseUrl: 'http://127.0.0.1:8000', expectedOpenapi: spec };
assert.equal((await probeBackend({ ...base, request: valid })).ok, true);
assert.equal((await probeBackend({ ...base, request: async () => { throw Error('PRIVATE'); } })).ok, false);
const offline = await probeBackend({ ...base, request: async () => { throw Error('PRIVATE'); } });
assert.ok(!JSON.stringify(offline).includes('PRIVATE'));
assert.equal((await probeBackend({ ...base, request: async (url: URL) => url.pathname === '/readyz' ? new Response('', { status: 503 }) : valid(url) })).ok, false);
assert.equal((await probeBackend({ ...base, request: async (url: URL) => url.pathname === '/openapi.json' ? Response.json({ paths: {} }) : valid(url) })).ok, false);
assert.equal((await probeBackend({ ...base, request: async (url: URL) => url.pathname === '/healthz' ? Response.json({ status: 'not_ok' }) : valid(url) })).ok, false);
assert.equal((await probeBackend({ ...base, request: async () => new Response('not JSON') })).ok, false);
assert.equal((await probeBackend({ ...base, request: async () => new Response('x'.repeat(2 * 1024 * 1024 + 1)) })).ok, false);
await assert.rejects(() => probeBackend({ ...base, baseUrl: 'http://user:private@localhost', request: valid }));
assert.equal(hash({ a: 1, b: 2 }), hash({ b: 2, a: 1 }));
assert.equal(resolveProfile({ a: { env: { API_BASE_URL: 'local' } }, b: { extends: 'a', env: { TEST: 'true' } } }, 'b').env.API_BASE_URL, 'local');
assert.throws(() => resolveProfile({ a: { extends: 'b' }, b: { extends: 'a' } }, 'a'));
console.log('previewBackendHealth: 12 tests passed (synthetic HTTP, no real backend writes)');
